/// 하니런 동전 한자 하나: 동전 이미지 번호와 말풍선 훈음.
class Hanja {
  const Hanja(this.no, this.text);

  /// 동전 이미지 번호. 예: y01 → assets/images/hani/run/coin-y01.png
  final String no;

  /// 말풍선에 쓰는 훈음. 예: 불 화
  final String text;

  @override
  String toString() => '$no($text)';
}

// shortcut: 서버(haniRunService)가 준비되기 전 임시 목록, 동전 이미지 순서대로 훈음을 넣음. 서버 데이터로 바뀌면 화면 확인용으로만 남김
/// 키코드 첫 글자로 과정별 동전 목록을 고른다. G 등 세트가 없는 과정은 y 사용
List<Hanja> runHanjaFor(String keyCode) => keyCode.toUpperCase().startsWith('S') ? runHanjaS : runHanjaY;

